function t(key, vars) {
  const lang = window._LANG || 'es';
  let str = (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) || (TRANSLATIONS['es'] && TRANSLATIONS['es'][key]) || key;
  if (vars) {
    Object.keys(vars).forEach(k => { str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), vars[k]); });
  }
  return str;
}

function setLang(lang) {
  window._LANG = lang;
  localStorage.setItem('lang', lang);
  document.documentElement.setAttribute('lang', lang);
  location.reload();
}

function toggleLang() {
  setLang(window._LANG === 'es' ? 'en' : 'es');
}
